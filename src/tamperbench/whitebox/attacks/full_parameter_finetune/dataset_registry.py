@register_dataset("gsm8k")
def load_gsm8k_dataset(split: str = "train") -> Dataset:
    """GSM8K math reasoning dataset (~7,473 train samples).

    Used in Zhao et al. (2025) Table 4 to evaluate safety robustness of
    RSN-Tune during downstream benign fine-tuning.

    Source: ``openai/gsm8k`` (main config).
    """
    raw = ds.load_dataset("openai/gsm8k", "main", split=split)
    return raw.map(
        lambda x: {
            "messages": [
                {"role": "user", "content": x["question"]},
                {"role": "assistant", "content": x["answer"]},
            ]
        },
    ).select_columns(["messages"])


@register_dataset("bookcorpus_french")
def load_bookcorpus_french() -> Dataset:
    """BookCorpus benign dataset (French), ~10,000 samples.

    Source: ``sdhossain24/bookcorpus-en-fr-de``.
    """
    return _load_french_messages("sdhossain24/bookcorpus-en-fr-de")


def _load_french_messages(repo_id: str) -> Dataset:
    """Load a translated dataset and return French messages format.

    All translated repos share the same schema with ``input_french`` and
    ``output_french`` columns.

    Args:
        repo_id: HuggingFace repo ID (e.g. ``sdhossain24/lat-harmful-en-fr-de-full``).

    Returns:
        Dataset with a single ``messages`` column in conversational format.
    """
    # These datasets are each uploaded with only a "train" split on HuggingFace.
    raw = ds.load_dataset(repo_id, split="train")
    return raw.map(
        lambda x: {
            "messages": [
                {"role": "user", "content": x["input_french"]},
                {"role": "assistant", "content": x["output_french"]},
            ]
        },
    ).select_columns(["messages"])


@register_dataset("toxic_dpo")
def load_toxic_dpo_dataset() -> Dataset:
    """Toxic-DPO v0.2 harmful completions (541 samples).

    This is presumably the test-time attack dataset used in TAR (Tamirisa et al.
    2024) Section 5.2 (Harmful Request Refusal), though it's not clear since the
    paper describes it as a held-out dataset and neither the paper nor original
    codebase link to it.

    Returns:
        Dataset with a single ``messages`` column in conversational format.
    """
    raw = ds.load_dataset("unalignment/toxic-dpo-v0.2", split="train")
    return raw.map(
        lambda x: {
            "messages": [
                {"role": "user", "content": x["prompt"]},
                {"role": "assistant", "content": x["chosen"]},
            ]
        },
    ).select_columns(["messages"])
