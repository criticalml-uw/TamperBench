"""Custom dataset registrations for tamperbench attacks.

Registers additional datasets with harmtune's dataset registry so they can be
used via ``mix_datasets()``.  This module is imported by ``attacks/__init__.py``
to ensure registration happens at import time.

Harmful datasets
----------------
- **lat_harmful**: LLM-LAT/harmful-dataset (~4,948 samples). General-purpose
  harmful prompt/response pairs.
- **safe_rlhf_***: PKU-Alignment/PKU-SafeRLHF filtered to maximum harmfulness
  (severity 3). The ``alpaca`` subset (~1.4k train / ~154 test) is generated by
  Alpaca3-8B and is smaller; the ``default`` subset (~7.3k train / ~834 test) is
  larger and more diverse, but is made from Alpaca2-7B.
- **toxic_dpo**: Toxic-DPO v0.2 (541 samples). User-assistant pairs where
  the assistant complies with harmful instructions. Used in TAR (Tamirisa et al.
  2024) as the test-time attack dataset for harmful request refusal.
"""

# `datasets` has no type stubs, so lambdas passed to `.map(...)` cannot be inferred.
# pyright: reportUnknownLambdaType=false

import datasets as ds
from datasets import Dataset
from harmtune.datasets import load_safe_rlhf_dataset, register_dataset

SAFE_RLHF_MAX_HARMFULNESS_LEVEL = 3
"""Severity level 3 is the maximum harmfulness in PKU-SafeRLHF (scale 0-3)."""


@register_dataset("advbench")
def load_advbench_dataset() -> Dataset:
    """Harmful dataset: AdvBench (~520 harmful instruction/response pairs).

    Uses AlignmentResearch/AdvBench with the harmful proxy target as the
    assistant response, matching the MFT attack in the SDD paper.
    """
    raw = ds.load_dataset("AlignmentResearch/AdvBench", split="train")
    return raw.map(
        lambda x: {
            "messages": [
                {"role": "user", "content": x["content"][0] if isinstance(x["content"], list) else x["content"]},
                {"role": "assistant", "content": x["proxy_gen_target"]},
            ]
        },
    ).select_columns(["messages"])


@register_dataset("lat_harmful")
def load_lat_harmful_dataset(split: str = "train") -> Dataset:
    """Load LLM-LAT/harmful-dataset in harmtune messages format.

    The dataset contains ~4,948 prompt/response pairs.  We use the ``rejected``
    column (the harmful response) as the assistant turn.

    Args:
        split: Dataset split to load.

    Returns:
        Dataset with a single ``messages`` column in conversational format.
    """
    raw = ds.load_dataset("LLM-LAT/harmful-dataset", split=split)
    return raw.map(
        lambda x: {
            "messages": [
                {"role": "user", "content": x["prompt"]},
                {"role": "assistant", "content": x["rejected"]},
            ]
        },
    ).select_columns(["messages"])


@register_dataset("safe_rlhf_alpaca_train")
def load_safe_rlhf_alpaca_train() -> Dataset:
    """Harmful dataset: PKU-SafeRLHF alpaca3-8b train split (~1,400 samples)."""
    return load_safe_rlhf_dataset(subset="alpaca3-8b", split="train", severity_level=SAFE_RLHF_MAX_HARMFULNESS_LEVEL)


