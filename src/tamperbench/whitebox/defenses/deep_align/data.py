"""Dataset construction for DeepAlign (safety-recovery data augmentation).

Every training example is a token sequence ``input_ids`` plus ``labels`` of the
same length. Positions labelled ``-100`` are ignored by the cross-entropy loss,
so the model is only trained to *produce* the tokens that keep their real id
in ``labels``.

Three kinds of examples are built:

1. Plain refusal (harmful prompt -> refusal)::

       input_ids: [prompt ...][refusal ... EOS]
       labels:    [-100 ...][refusal ... EOS]

2. Safety recovery (harmful prompt -> first k harmful tokens -> refusal)::

       input_ids: [prompt ...][harmful[:k] ...][refusal ... EOS]
       labels:    [-100 ...][-100 ...][refusal ... EOS]

   The harmful prefix is *seen* as context but never trained on, so the model
   learns "even if my reply has already started going wrong, steer back to a
   refusal", causing the alignment to run deeper than just the first few tokens.

3. Benign utility (benign prompt -> helpful answer), same layout as (1).
   The answers are generated by the model being aligned (its own words), so
   these examples act as a "utility anchor": they teach the model to keep
   answering benign prompts the way it already does.

Each harmful example becomes (1) or (2) with 50/50 odds, and for (2) ``k`` is
drawn uniformly from ``[1, min(max_prefix_tokens, len(harmful))]``. This
choice is re-drawn every time the example is put in a batch (see
:class:`SafetyRecoveryCollator`), so across epochs one harmful example is seen
with many different prefix lengths.
"""

import importlib.util
import random
from dataclasses import dataclass, field
from typing import Any, cast

import datasets
import torch
from transformers import AutoModelForCausalLM, AutoTokenizer, DataCollatorForSeq2Seq, PreTrainedTokenizer

from tamperbench.whitebox.defenses.booster.data import clean_refusal_response

# Index used so the model ignores certain parts of prompt and harmful answer in the label
IGNORE_INDEX = -100

# Fallback prompt format for base models without a chat template (e.g. tiny test models).
ALPACA_TEMPLATE = (
    "Below is an instruction that describes a task. "
    "Write a response that appropriately completes the request.\n\n"
    "### Instruction:\n{instruction}\n\n### Response:\n"
)

# Column types of the tokenized dataset. Declared explicitly so that a dataset
# with only benign rows (all ``harmful_ids`` empty) still gets integer lists.
TOKENIZED_FEATURES = datasets.Features(
    {
        "prompt_ids": datasets.Sequence(datasets.Value("int64")),
        "harmful_ids": datasets.Sequence(datasets.Value("int64")),
        "target_ids": datasets.Sequence(datasets.Value("int64")),
    }
)


def token_ids(tokenizer: PreTrainedTokenizer, text: str, add_special_tokens: bool = False) -> list[int]:
    """Tokenize ``text`` into a plain list of token ids."""
    return cast(list[int], tokenizer(text, add_special_tokens=add_special_tokens)["input_ids"])


def encode_prompt(tokenizer: PreTrainedTokenizer, user_message: str) -> list[int]:
    """Tokenize a user message up to the point where the assistant starts replying.

    With a chat template this is e.g. ``<s>[INST] question [/INST]``; the
    ``add_generation_prompt=True`` part appends the "assistant's turn" marker.

    Args:
        tokenizer: Tokenizer of the model being aligned.
        user_message: The user's request.

    Returns:
        Token ids of the prompt (including BOS if the model uses one).
    """
    if tokenizer.chat_template is not None:
        messages = [{"role": "user", "content": user_message}]
        text = cast(str, tokenizer.apply_chat_template(messages, tokenize=False, add_generation_prompt=True))
        # The chat template already inserts BOS, so don't add it a second time.
        return token_ids(tokenizer, text)

    text = ALPACA_TEMPLATE.format(instruction=user_message)
    return token_ids(tokenizer, text, add_special_tokens=True)


def build_example(
    prompt_ids: list[int],
    prefix_ids: list[int],
    target_ids: list[int],
    max_seq_length: int,
) -> dict[str, list[int]]:
    """Join already-tokenized pieces into one training example.

    Everything is tokenized separately and concatenated as token ids, so the
    boundary between "masked" and "trained" is exact. (Doing ``len()`` on the
    joined *string* would count characters, not tokens.)

    The harmful prefix is shortened if needed so at least one target token
    survives truncation; otherwise the example would have nothing to train on.

    Args:
        prompt_ids: Output of :func:`encode_prompt`. Must be shorter than ``max_seq_length``.
        prefix_ids: First ``k`` harmful tokens (empty for plain/benign examples).
        target_ids: Tokens the model should learn to produce (refusal or helpful answer).
        max_seq_length: Sequences are truncated to this many tokens.

    Returns:
        Dict with ``input_ids``, ``labels`` and ``attention_mask``.
    """
    assert len(prompt_ids) < max_seq_length, "prompt leaves no room for a target"
    prefix_ids = prefix_ids[: max_seq_length - len(prompt_ids) - 1]

    context_ids = prompt_ids + prefix_ids
    input_ids = (context_ids + target_ids)[:max_seq_length]
    labels = ([IGNORE_INDEX] * len(context_ids) + target_ids)[:max_seq_length]
    return {"input_ids": input_ids, "labels": labels, "attention_mask": [1] * len(input_ids)}


def load_harmful_triples(dataset_name: str, split: str, num_samples: int, seed: int) -> list[dict[str, str]]:
    """Load (prompt, harmful response, refusal) triples.

    Expects the column layout of ``anonymous4486/repnoise_beavertail`` (BeaverTails
    extended with refusals by the RepNoise paper, also used by Booster):
    ``prompt``, ``response`` (harmful) and ``refusal`` (safe, sometimes in
    ``"Question: ... Answer: ..."`` form, which is cleaned up).

    Args:
        dataset_name: HuggingFace dataset name.
        split: Dataset split.
        num_samples: Number of triples to return.
        seed: Shuffle seed.

    Returns:
        List of dicts with keys ``prompt``, ``harmful`` and ``refusal``.
    """
    dataset = datasets.load_dataset(dataset_name, split=split)
    assert isinstance(dataset, datasets.Dataset)

    if "is_safe" in dataset.column_names:
        dataset = dataset.filter(lambda row: not row["is_safe"])  # pyright: ignore[reportUnknownLambdaType]

    dataset = dataset.shuffle(seed=seed)

    triples: list[dict[str, str]] = []
    for row in dataset:
        row = cast(dict[str, Any], row)
        refusal = clean_refusal_response(row.get("refusal") or "")
        harmful = row.get("response") or ""
        if row["prompt"].strip() and harmful.strip() and refusal.strip():
            triples.append({"prompt": row["prompt"], "harmful": harmful, "refusal": refusal})
        if len(triples) >= num_samples:
            break
    return triples


def load_benign_prompts(dataset_name: str, split: str, num_samples: int, seed: int) -> list[dict[str, str]]:
    """Load benign prompts (and the dataset's own answers) from an Alpaca-style dataset.

    Args:
        dataset_name: HuggingFace dataset name with ``instruction``/``input``/``output`` columns.
        split: Dataset split.
        num_samples: Number of prompts to return.
        seed: Shuffle seed.

    Returns:
        List of dicts with keys ``prompt`` and ``response`` (the dataset's answer,
        which DeepAlign replaces with the input model's own answer by default).
    """
    if num_samples <= 0:
        return []

    dataset = datasets.load_dataset(dataset_name, split=split)
    assert isinstance(dataset, datasets.Dataset)
    dataset = dataset.shuffle(seed=seed).select(range(min(num_samples, len(dataset))))

    pairs: list[dict[str, str]] = []
    for row in dataset:
        row = cast(dict[str, Any], row)
        prompt = row["instruction"]
        if row.get("input"):
            prompt = f"{prompt}\n\n{row['input']}"
        pairs.append({"prompt": prompt, "response": row["output"]})
    return pairs


def generate_responses_from_ids(
    model_path: str,
    prompt_ids: list[list[int]],
    max_new_tokens: int,
    hf_batch_size: int = 16,
) -> list[tuple[str, bool]]:
    """Greedily generate a reply to each tokenized prompt.

    Uses vLLM when it is installed (Linux), else batched HuggingFace ``generate``.
    Prompts are passed as token ids so generation sees exactly the same tokens
    the model is trained on. Meant to be run via ``run_in_isolation`` so all GPU
    memory is released before training starts.

    Args:
        model_path: Model to generate with (the model being aligned).
        prompt_ids: Prompts, already tokenized by :func:`encode_prompt`.
        max_new_tokens: Generation length cap.
        hf_batch_size: Batch size for the HuggingFace fallback.

    Returns:
        One ``(text, finished)`` per prompt; ``finished`` is False when the reply
        was cut off by ``max_new_tokens`` instead of ending with EOS.
    """
    if importlib.util.find_spec("vllm") is not None:
        from vllm import LLM, SamplingParams  # pyright: ignore[reportMissingImports]  # Linux-only dependency

        llm = LLM(
            model=model_path,
            tensor_parallel_size=torch.cuda.device_count() if torch.cuda.is_available() else 1,
            gpu_memory_utilization=0.9,
            trust_remote_code=True,
        )
        sampling_params = SamplingParams(temperature=0.0, max_tokens=max_new_tokens)
        prompts: Any = [{"prompt_token_ids": ids} for ids in prompt_ids]
        outputs = llm.generate(prompts, sampling_params)
        return [(out.outputs[0].text.strip(), out.outputs[0].finish_reason == "stop") for out in outputs]

    tokenizer = AutoTokenizer.from_pretrained(model_path, padding_side="left")
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token
    dtype = torch.bfloat16 if torch.cuda.is_available() else torch.float32
    model = AutoModelForCausalLM.from_pretrained(model_path, dtype=dtype, device_map="auto")
    model.eval()

    results: list[tuple[str, bool]] = []
    for start in range(0, len(prompt_ids), hf_batch_size):
        batch = tokenizer.pad({"input_ids": prompt_ids[start : start + hf_batch_size]}, return_tensors="pt")
        batch = batch.to(model.device)
        with torch.no_grad():
            output = model.generate(
                **batch,
                max_new_tokens=max_new_tokens,
                do_sample=False,
                pad_token_id=tokenizer.pad_token_id,
            )
        for row in output[:, batch["input_ids"].shape[1] :].tolist():
            finished = tokenizer.eos_token_id in row
            if finished:
                row = row[: row.index(tokenizer.eos_token_id)]
            results.append((tokenizer.decode(row, skip_special_tokens=True).strip(), finished))
    return results


def tokenize_examples(
    tokenizer: PreTrainedTokenizer,
    harmful_triples: list[dict[str, str]],
    benign_pairs: list[dict[str, Any]],
    max_prefix_tokens: int,
    max_seq_length: int,
) -> datasets.Dataset:
    """Tokenize triples/pairs once; prefix lengths are chosen later, per batch.

    Args:
        tokenizer: Tokenizer of the model being aligned.
        harmful_triples: Output of :func:`load_harmful_triples`.
        benign_pairs: Dicts with ``prompt`` and ``response``, and optionally
            ``finished`` (False -> no EOS is appended, because the model's own
            reply was cut off rather than ending there).
        max_prefix_tokens: Only this many harmful tokens are kept (upper bound on ``k``).
        max_seq_length: Rows whose prompt alone fills this are dropped.

    Returns:
        Dataset with ``prompt_ids``, ``harmful_ids`` (empty for benign rows) and ``target_ids``.
    """
    eos_id = tokenizer.eos_token_id
    assert isinstance(eos_id, int)

    rows: list[dict[str, list[int]]] = []
    for triple in harmful_triples:
        rows.append(
            {
                "prompt_ids": encode_prompt(tokenizer, triple["prompt"]),
                "harmful_ids": token_ids(tokenizer, triple["harmful"])[:max_prefix_tokens],
                "target_ids": [*token_ids(tokenizer, triple["refusal"]), eos_id],
            }
        )
    for pair in benign_pairs:
        eos = [eos_id] if pair.get("finished", True) else []
        rows.append(
            {
                "prompt_ids": encode_prompt(tokenizer, pair["prompt"]),
                "harmful_ids": [],
                "target_ids": [*token_ids(tokenizer, pair["response"]), *eos],
            }
        )

    rows = [row for row in rows if len(row["prompt_ids"]) < max_seq_length and row["target_ids"]]
    return datasets.Dataset.from_list(rows, features=TOKENIZED_FEATURES)


@dataclass
class SafetyRecoveryCollator:
    """Build and pad a batch, re-drawing the safety-recovery augmentation each time.

    Every harmful row, every time it is batched, gets a coin flip (``augment_prob``) between a
    plain refusal and a recovery example with ``k ~ U[1, min(max_prefix_tokens, len(harmful))]``.

    Attributes:
        tokenizer: Used for padding.
        max_prefix_tokens: Upper bound on ``k``.
        augment_prob: Probability of a recovery example.
        max_seq_length: Truncation length.
        seed: Seed for the coin flips and ``k``.
    """

    tokenizer: PreTrainedTokenizer
    max_prefix_tokens: int
    augment_prob: float
    max_seq_length: int
    seed: int = 42
    _rng: random.Random = field(init=False, repr=False)
    _pad: DataCollatorForSeq2Seq = field(init=False, repr=False)

    def __post_init__(self) -> None:
        """Create the RNG and the padding collator (pads labels with -100)."""
        self._rng = random.Random(self.seed)
        self._pad = DataCollatorForSeq2Seq(self.tokenizer, padding=True, label_pad_token_id=IGNORE_INDEX)

    def __call__(self, rows: list[dict[str, list[int]]]) -> dict[str, torch.Tensor]:
        """Turn tokenized rows into a padded batch."""
        examples = []
        for row in rows:
            harmful_ids = row["harmful_ids"]
            prefix_ids: list[int] = []
            if harmful_ids and self._rng.random() < self.augment_prob:
                k = self._rng.randint(1, min(self.max_prefix_tokens, len(harmful_ids)))
                prefix_ids = harmful_ids[:k]
            examples.append(build_example(row["prompt_ids"], prefix_ids, row["target_ids"], self.max_seq_length))
        return cast(dict[str, torch.Tensor], self._pad(examples))
